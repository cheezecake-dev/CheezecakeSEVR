    /// <summary>
    /// A screen showing the ship (or the character on foot) from a chase camera behind and above it, while the player
    /// stays in first person; or the view from one of the ship's camera blocks (<see cref="ExternalViewSource"/> says which,
    /// and the actions wheel chooses). A third scene pass, drawn after the eyes through the same DrawGameScene the eyes use,
    /// into a small texture; on the desktop it is laid over the lower left of each eye's part of the window, in the headset
    /// it is an extra quad layer on the dash (see <see cref="XrSession.Screen"/>).
    /// </summary>
    /// <remarks>
    /// Why a pass from a different place can see its own view: the engine culls inside each DrawGameScene, from
    /// Environment.Matrices (ViewFrustumClippedD and CameraPosition; MyCullManager.InitFrame -> MyCullQueries.AddMainViewPass),
    /// not once per frame from the game's camera. Setting the matrices as <see cref="EnvMatrices.MakeEye"/> does for an
    /// eye - the view moved, CameraPosition left at the head - therefore culls, lights and draws from the chase camera.
    ///
    /// The pass is small (<see cref="TextureWidth"/> x <see cref="TextureHeight"/>) but the renderer sizes its screen
    /// resources (GBuffer, light tiles, auto-exposure) once, from m_resolution, so it gets a set of its own that is
    /// swapped in around the pass (<see cref="SwapIn"/>), together with m_resolution, ViewportResolution and
    /// FullResViewport. Everything else the pass would leave behind for the eyes' next frame is kept out of it: sun
    /// shadows (the cascades are cached between passes), spot light shadows (and their list), flares and group occlusion
    /// queries (the eyes would be culled by what the chase camera could not see: <c>MyActor.IsOccluded</c> is patched off for the
    /// pass), foliage and GPU particles (simulated and generated by each pass), and SSAO (its textures are screen sized).
    ///
    /// The same pass, picture and screen layer also serve two views that are not the dash screen's (<see cref="Kind"/>),
    /// each taking the screen's place while it lasts: the zoom inset (<see cref="ZoomInset"/>), the game's zoomed view
    /// through the block the player looks through, on a small screen where the player was looking; and the death view
    /// (<see cref="DeathView"/>), the game's own camera while dead or choosing where to respawn, on a screen ahead. Neither
    /// can be taken hold of; the dash screen comes back where it was when they end.
    /// </remarks>
    internal static class ExternalView
    {
        public const int TextureWidth = 640, TextureHeight = 360;

        /// <summary>What the picture is for in a frame: chosen on the game thread as the camera goes to the renderer, kept with it.</summary>
        internal enum Kind : byte
        {
            /// <summary>No picture: the screen is off (or has nothing to show), and nothing else wants one.</summary>
            None,

            /// <summary>The screen on the dash: the chase camera, or the camera block chosen for it.</summary>
            Screen,

            /// <summary>The zoom inset (<see cref="ZoomInset"/>): the game's zoomed view through the camera the player looks through.</summary>
            Zoom,

            /// <summary>The death view (<see cref="DeathView"/>): the game's own camera while dead or choosing where to respawn.</summary>
            Death,
        }

        /// <summary>The chase camera's vertical field of view, degrees.</summary>
        private const float FieldOfViewDegrees = 60f;

        /// <summary>The widest and the narrowest vertical field of view a camera block's picture is drawn with, radians.</summary>
        private const float MinFieldOfView = 0.1f, MaxFieldOfView = 2.5f;

        /// <summary>A picture older than this (seconds) is no longer shown: nothing to chase, or the pass keeps failing.</summary>
        private const double FreshSeconds = 1.0;

        /// <summary>A camera snapshot older than this (seconds) is not used for a pass.</summary>
        private const double SnapshotSeconds = 0.5;

        /// <summary>Where the screen stands on the dash, from the head at rest: right, up, forward (negative z), metres.</summary>
        private static readonly Vector3 DashOffset = new Vector3(-0.20f, -0.30f, -0.60f);

        /// <summary>The highest and the lowest the third-person camera goes round what it follows, radians from its horizon: short of straight over or under, where "up" would say nothing about which way the picture is turned.</summary>
        public const float MaxLiftDegrees = 80f;

        private const double MaxLift = MaxLiftDegrees * Math.PI / 180.0;

        /// <summary>The farthest a screen moved by hand may stand from the head when it appears again, metres (a placement from the file further out is put back on the dash).</summary>
        private const float MaxPlaceDistance = 3f;

        private static readonly Assembly Render11 = typeof(MyDX11Render).Assembly;

        /// <summary>
        /// Debug (<see cref="RenderDebug"/> ExternalView=1 / 0): forced on or off whatever the setting says. Null follows the setting.
        /// </summary>
        public static bool? Debug { get; set; }

        /// <summary>Everything the pass needs was found, and nothing has failed yet.</summary>
        private static volatile bool available;

        /// <summary>True while the pass is being drawn. Read by the culling workers (<see cref="SkipOcclusion"/>).</summary>
        private static volatile bool drawing;

        /// <summary>The screen is on: the setting or the debug switch, and the pass works.</summary>
        public static bool Wanted => available && On;

        /// <summary>The screen is switched on: RenderDebug's override if there is one, else the setting (whether or not the pass works).</summary>
        public static bool On => Debug ?? VRSettings.ExternalViewOn;

        /// <summary>The pass works (it is turned off for the rest of the run after a failure).</summary>
        public static bool Usable => available;

        // ---- reflection: the renderer's own members ----
        private static Type render, gbufferType, lightsType, eyeAdaptationType, managersType;
        private static FieldInfo resolution, fullResViewport, gbufferMain, gbufferSamples, gbufferQuality, gbufferHdr;
        private static PropertyInfo viewportResolution, debugOverrides;
        private static MethodInfo gbufferResize, gbufferRelease, lightsResize, lightsDispose;
        private static FieldInfo[] lightFields;
        private static FieldInfo autoExposure, rwTextures, shadowsManager, tempShadowLights;
        private static MethodInfo createRtv, disposeRtv, copyResourceToResource, occlusionRender;

        // ---- the camera, from the game thread ----
        private const int Capacity = 16;
        private static readonly object gate = new object();
        private static readonly MatrixD[] views = new MatrixD[Capacity];
        private static readonly MatrixD[] poses = new MatrixD[Capacity];
        private static readonly float[] fields = new float[Capacity];
        private static readonly float[] zooms = new float[Capacity];
        private static readonly Kind[] kinds = new Kind[Capacity];
        private static readonly long[] stamps = new long[Capacity];
        private static int next;
        private static int misses;
        private static bool captureFailureLogged;

        // ---- this frame's camera, found on the render thread before the eyes (Find) ----
        private static Kind frameKind, lastKind, drawnKind;
        private static Matrix framePose;
        private static float frameField, frameZoom;
        private static bool noHeadsetNoted;

        // ---- the picture and the screen resources, on the render thread ----
        private static object texture;
        private static long drawnAt;
        private static bool haveImage;
        private static object smallGBuffer;
        private static object[] smallLights;
        private static object smallExposure;
        private static bool screenSetBuilt, screenSetJustBuilt;
        private static bool placed;
        private static Matrix dash;
        private static XrSession.Screen? pending;

        /// <summary>The pass has drawn the dash screen's picture lately, and the screen is on.</summary>
        public static bool Showing => Wanted && haveImage && drawnKind == Kind.Screen && Seconds(Stopwatch.GetTimestamp() - drawnAt) < FreshSeconds;

        private static double Seconds(long ticks) => (double)ticks / Stopwatch.Frequency;

        public static void Patch(Harmony harmony)
        {
            try
            {
                Resolve();
            }
            catch (Exception e)
            {
                Log.Error(e, "External view: the renderer's members were not found; the screen is off");
                return;
            }

            try
            {
                harmony.Patch(AccessTools.Method(typeof(MyRenderProxy), nameof(MyRenderProxy.SetCameraViewMatrix)),
                    postfix: new HarmonyMethod(typeof(ExternalView), nameof(Capture)));
                harmony.Patch(AccessTools.Method(typeof(VRage.Render.Scene.MyActor), nameof(VRage.Render.Scene.MyActor.IsOccluded)),
                    prefix: new HarmonyMethod(typeof(ExternalView), nameof(SkipOcclusion)));
                harmony.Patch(occlusionRender, prefix: new HarmonyMethod(typeof(ExternalView), nameof(SkipOcclusionQueries)));
                harmony.Patch(AccessTools.Method(render, "CreateScreenResources"),
                    postfix: new HarmonyMethod(typeof(ExternalView), nameof(ScreenResourcesChanged)));
                available = true;
                Log.Info("External view patched");
            }
            catch (Exception e)
            {
                Log.Error(e, "External view could not be hooked; the screen is off");
            }
        }

