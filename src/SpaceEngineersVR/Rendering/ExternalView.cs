        }

        private static FieldInfo Field(Type type, string name) =>
            AccessTools.Field(type, name) ?? throw new MissingFieldException(type.Name, name);

        // ------------------------------------------------------------------------------------------------------
        // Game thread: where the chase camera is
        // ------------------------------------------------------------------------------------------------------

        /// <summary>
        /// Game thread, as the camera goes to the renderer: what the picture is for this frame (<see cref="Kind"/>) and, for
        /// the dash screen, the chase camera, in the game camera's own space; for the zoom inset and the death view, the
        /// game camera's field of view (and the zoom). Keyed by the view matrix so that the renderer, which may be a message
        /// behind, pairs it with the ship as that frame drew it (the same way <see cref="Tracking.CameraHeadLink"/> pairs
        /// the head). A frame that wants no picture is kept too, so the renderer never takes an older frame's for it.
        /// </summary>
        private static void Capture(MatrixD viewMatrix)
        {
            if (!available)
                return;
            try
            {
                Kind kind = Kind.None;
                MatrixD pose = MatrixD.Identity;
                float field = 0f, zoom = 1f;
                if (DeathView.Wanted())
                {
                    kind = Kind.Death;
                    field = GameField();
                }
                else if (ZoomInset.Wanted(out zoom))
                {
                    kind = Kind.Zoom;
                    field = GameField();
                }
                else if (On && TryViewpoint(out MatrixD camera, out field))
                {
                    kind = Kind.Screen;
                    pose = camera * viewMatrix;
                }
                lock (gate)
                {
                    views[next] = viewMatrix;
                    poses[next] = pose;
                    fields[next] = field;
                    zooms[next] = zoom;
                    kinds[next] = kind;
                    stamps[next] = Stopwatch.GetTimestamp();
                    next = (next + 1) % Capacity;
                }
            }
            catch (Exception e)
            {
                if (!captureFailureLogged)
                {
                    captureFailureLogged = true;
                    Log.Error(e, "External view: could not place the chase camera");
                }
            }
        }

        /// <summary>The game camera's vertical field of view, radians, within what the pass draws with.</summary>
        private static float GameField() =>
            MathHelper.Clamp(MySector.MainCamera?.FieldOfView ?? MathHelper.ToRadians(FieldOfViewDegrees), 1e-4f, MaxFieldOfView);

        /// <summary>
        /// Where the picture is taken from this frame: the chosen camera block's view (its world matrix and field of view,
        /// read only: the player's own view is never moved to it, and the block is never made the active camera), or the
        /// chase camera when that is the source, or when the chosen camera cannot be used now (<see cref="ExternalViewSource"/>
        /// says so once).
        /// </summary>
        private static bool TryViewpoint(out MatrixD camera, out float field)
        {
            field = MathHelper.ToRadians(FieldOfViewDegrees);
            if (ExternalViewSource.TryCameraView(out camera, out float cameraField))
            {
                field = MathHelper.Clamp(cameraField, MinFieldOfView, MaxFieldOfView);
                return true;
            }
            return TryChaseCamera(out camera);
        }

        /// <summary>
        /// The chase camera's world matrix: behind and above what the player controls, looking at it, horizon level
        /// (up is against natural gravity; in space, up is the ship's own).
        /// </summary>
        private static bool TryChaseCamera(out MatrixD camera)
        {
            camera = MatrixD.Identity;
            MySession session = MySession.Static;
            var controlled = session?.ControlledEntity;
            if (controlled == null || session.IsCameraUserControlledSpectator())
                return false;

            MatrixD frame;
            Vector3D center;
            double distance, height;
            MyEntity entity = controlled.Entity;
            bool onFoot = entity is MyCharacter;
            if (entity is MyCharacter character)
            {
                frame = character.PositionComp.WorldMatrixRef;
                center = frame.Translation + frame.Up * 1.0;
                distance = 3.5;
                height = 1.0;
            }
            else
            {
                MyCubeGrid grid = (entity as MyCubeBlock)?.CubeGrid ?? entity?.GetTopMostParent() as MyCubeGrid;
                if (grid == null)
                    return false;
                frame = grid.PositionComp.WorldMatrixRef;
                BoundingSphereD volume = grid.PositionComp.WorldVolume;
                center = volume.Center;
                distance = MathHelper.Clamp(volume.Radius * 2.4 + 3.0, 6.0, 400.0);
                height = distance * 0.28;
            }

            // The wrist panel's External view page: nearer or farther (a multiple, so it suits a character and the biggest
            // station alike), and round and over or under what is followed, on the sphere through where the camera starts.
            double scale = VRSettings.ExternalViewDistance;
            distance *= scale;
            height *= scale;
            ChaseRadius = Math.Sqrt(distance * distance + height * height);
            ChasingCharacter = onFoot;

            Vector3 gravity = MyGravityProviderSystem.CalculateNaturalGravityInPoint(center);
            return Compose(frame, center, gravity, distance, height,
                MathHelper.ToRadians(VRSettings.ExternalViewOrbit), MathHelper.ToRadians(VRSettings.ExternalViewElevation), out camera);
        }

        /// <summary>The third-person camera's distance from what it follows, metres, the last time it was placed (for the wrist panel's words). Zero before then.</summary>
        public static double ChaseRadius { get; private set; }

        /// <summary>The third-person camera followed a character (on foot) the last time it was placed, not a grid.</summary>
        public static bool ChasingCharacter { get; private set; }

        /// <summary>Where the third-person camera starts, degrees over what it follows: its height over its distance, as <see cref="TryChaseCamera"/> sets them (the same for a character and a grid, near enough).</summary>
        public const float StartLiftDegrees = 15.6f;

        /// <summary>The camera's height over its horizon, degrees, for an elevation (<see cref="VRSettings.ExternalViewElevation"/>), clamped as <see cref="Compose"/> clamps it.</summary>
        public static float LiftDegrees(float elevation) =>
            MathHelper.Clamp(StartLiftDegrees + elevation, -MaxLiftDegrees, MaxLiftDegrees);

        /// <summary>
        /// The chase camera for something at <paramref name="center"/> facing along <paramref name="frame"/>'s forward:
        /// <paramref name="distance"/> behind it along the horizon and <paramref name="height"/> above, looking at it,
        /// with the horizon level. Up is against <paramref name="gravity"/> where there is any, else the frame's own up.
        /// Then taken round it on the sphere through that point: <paramref name="orbit"/> radians round the up axis (positive
        /// to its left) and <paramref name="elevation"/> radians over it (negative under), never past <see cref="MaxLift"/>;
        /// it always looks at the centre.
        /// </summary>
        internal static bool Compose(in MatrixD frame, Vector3D center, Vector3 gravity, double distance, double height,
                                     double orbit, double elevation, out MatrixD camera)
        {
            camera = MatrixD.Identity;
            Vector3D up = frame.Up;
            if (gravity.LengthSquared() > 1e-4f)
                up = -Vector3D.Normalize((Vector3D)gravity);

            // Which way the ship faces along the horizon. Pointing nearly straight up or down, its forward says nothing
            // about that: use the way its top points then, as the world menu does for a head looking up or down.
            Vector3D forward = frame.Forward;
            Vector3D along = forward - up * forward.Dot(up);
            if (along.LengthSquared() < 0.04)
            {
                Vector3D top = frame.Up;
                along = top - up * top.Dot(up);
                if (forward.Dot(up) > 0.0)
                    along = -along;
            }
            if (along.LengthSquared() < 1e-6)
                along = Vector3D.Cross(up, frame.Right);
            if (along.LengthSquared() < 1e-6)
                return false;
            along.Normalize();

            double radius = Math.Sqrt(distance * distance + height * height);
            double lift = MathHelper.Clamp(Math.Atan2(height, distance) + elevation, -MaxLift, MaxLift);
            // Round the up axis: a positive turn takes "behind" toward the right, so the left is the negative one.
            Vector3D behind = Vector3D.Transform(-along, MatrixD.CreateFromAxisAngle(up, -orbit));
            Vector3D eye = center + (behind * Math.Cos(lift) + up * Math.Sin(lift)) * radius;
            camera = MatrixD.CreateWorld(eye, Vector3D.Normalize(center - eye), up);
            return true;
        }

        // ------------------------------------------------------------------------------------------------------
        // Render thread: the pass
        // ------------------------------------------------------------------------------------------------------

        /// <summary>
        /// Render thread, before the eyes are drawn: finds the camera the renderer holds among those the game sent, and with
        /// it what the picture is for this frame (<see cref="Kind"/>), for <see cref="Render"/> and the screen. The zoom inset
        /// needs a headset: without one the eyes are drawn with the game camera's own field of view, so they zoom as a
        /// monitor does already. Never throws.
        /// </summary>
        /// <param name="env">The renderer's environment matrices, as the head camera.</param>
        /// <param name="headset">This frame goes to the headset.</param>
        public static Kind Find(object env, bool headset)
        {
            frameKind = Kind.None;
            if (!available)
                return Kind.None;
            try
            {
                if (!TryGetPose(env, out Matrix pose, out float field, out float zoom, out Kind kind))
                    return Kind.None;
                if (kind == Kind.Zoom && !headset)
                {
                    if (!noHeadsetNoted)
                        Log.Info("Zoom inset: no headset, so the eyes are drawn with the game's zoomed field of view, as on a monitor; no inset");
                    noHeadsetNoted = true;
                    kind = Kind.None;
                }
                framePose = pose;
                frameField = field;
                frameZoom = zoom;
                frameKind = kind;
            }
            catch (Exception e)
            {
                available = false;
                haveImage = false;
                Log.Error(e, "External view: finding this frame's camera failed; the screen, the zoom inset and the death view are off for the rest of the run");
            }
            return frameKind;
        }

        /// <summary>
        /// Draws this frame's picture (<see cref="Find"/> says which) after the eyes, and puts the head camera back: the dash
        /// screen's view (every other frame with <see cref="VRSettings.ExternalViewHalfRate"/>), the zoom inset's (every other
        /// frame with <see cref="ZoomInset.HalfRate"/>) or the death view's. Never throws; on a failure the screen turns itself off.
        /// </summary>
        /// <param name="env">The renderer's environment matrices, as the head camera.</param>
        /// <param name="head">The head camera, to put back.</param>
        /// <param name="trackingToCamera">From the tracking space into the game camera's, as the eyes are placed (the head
        /// the camera already holds taken out), without the eyes' extrapolation shift, which is undone before this pass.</param>
        public static void Render(object env, in EnvMatrices.Snapshot head, int frame, in Matrix trackingToCamera)
        {
            try
            {
                RenderPass(env, head, frame, trackingToCamera);
            }
            catch (Exception e)
            {
                available = false;
                haveImage = false;
                Log.Error(e, "External view: the chase pass could not start; the screen is off for the rest of the run");
            }
        }

        private static void RenderPass(object env, in EnvMatrices.Snapshot head, int frame, in Matrix trackingToCamera)
        {
            Kind kind = available ? frameKind : Kind.None;
            bool changed = kind != lastKind;
            if (changed)
                Switched(lastKind, kind);
            lastKind = kind;
            if (kind == Kind.None)
            {
                // Nothing to draw this frame. With the screen on, it keeps its place and its last picture for a moment.
                if (!Wanted)
                {
                    haveImage = false;
                    placed = false;
                    passTimed = false;
                }
                return;
            }
            bool halfRate = kind == Kind.Zoom ? ZoomInset.HalfRate : kind == Kind.Screen && VRSettings.ExternalViewHalfRate;
            if (haveImage && !changed && halfRate && (frame & 1) != 0)
                return;

            Matrix eyeFromHead;
            EnvMatrices.FovTangents fov;
            Matrix tracking = EyeRenderer.Head;
            switch (kind)
            {
                case Kind.Zoom:
                    eyeFromHead = ZoomInset.Eye(tracking, frameZoom, out fov) * trackingToCamera;
                    break;
                case Kind.Death:
                    // The game's own camera, without the head it may hold: where the death camera or the respawn screen put it.
                    DeathView.Place(tracking);
                    eyeFromHead = trackingToCamera;
                    fov = Tangents(frameField);
                    break;
                default:
                    eyeFromHead = framePose;
                    fov = Tangents(frameField);
                    break;
            }
            long started = Stopwatch.GetTimestamp();
            bool first = !passTimed;

            MyRenderDebugOverrides overrides = (MyRenderDebugOverrides)debugOverrides.GetValue(null);
            bool shadows = overrides.Shadows, spotLights = overrides.SpotLights, flares = overrides.Flares,
                foliage = overrides.Foliage, particles = overrides.GPUParticles, ssao = overrides.SSAO;
            IList shadowLights = (IList)tempShadowLights.GetValue(shadowsManager.GetValue(null));
            var savedShadowLights = new ArrayList(shadowLights);
            Vector2I bigResolution = (Vector2I)resolution.GetValue(null);
            Vector2I bigViewport = (Vector2I)viewportResolution.GetValue(null);
            object bigFullRes = fullResViewport.GetValue(null);
            object bigGBuffer = gbufferMain.GetValue(null);
            object[] bigLights = new object[lightFields.Length];
            for (int i = 0; i < bigLights.Length; i++)
                bigLights[i] = lightFields[i].GetValue(null);
            object bigExposure = autoExposure.GetValue(null);

            try
            {
                EnsureTexture();
                EnsureScreenSet();

                resolution.SetValue(null, new Vector2I(TextureWidth, TextureHeight));
                viewportResolution.SetValue(null, new Vector2I(TextureWidth, TextureHeight));
                fullResViewport.SetValue(null, new MyViewport(TextureWidth, TextureHeight));
                gbufferMain.SetValue(null, smallGBuffer);
                for (int i = 0; i < smallLights.Length; i++)
                    lightFields[i].SetValue(null, smallLights[i]);
                autoExposure.SetValue(null, smallExposure);

                overrides.Shadows = overrides.SpotLights = overrides.Flares = overrides.Foliage = overrides.GPUParticles = overrides.SSAO = false;
                drawing = true;

                EnvMatrices.MakeEye(env, eyeFromHead, fov);
                ScenePass.Current = ScenePass.Chase;
                try
                {
                    EyeRenderer.DrawSceneTo(texture);
                }
                finally
                {
                    ScenePass.Current = ScenePass.None;
                }

                drawnAt = Stopwatch.GetTimestamp();
                haveImage = true;
                drawnKind = kind;
                TimePass(first, drawnAt - started);
            }
            catch (Exception e)
            {
                available = false;
                haveImage = false;
                Log.Error(e, "External view: the chase pass failed; the screen is off for the rest of the run");
            }
            finally
            {
                drawing = false;
                overrides.Shadows = shadows;
                overrides.SpotLights = spotLights;
                overrides.Flares = flares;
                overrides.Foliage = foliage;
                overrides.GPUParticles = particles;
                overrides.SSAO = ssao;
                shadowLights.Clear();
                foreach (object light in savedShadowLights)
                    shadowLights.Add(light);

                autoExposure.SetValue(null, bigExposure);
                for (int i = 0; i < bigLights.Length; i++)
                    lightFields[i].SetValue(null, bigLights[i]);
                gbufferMain.SetValue(null, bigGBuffer);
                fullResViewport.SetValue(null, bigFullRes);
                viewportResolution.SetValue(null, bigViewport);
                resolution.SetValue(null, bigResolution);
                EnvMatrices.Restore(env, head);
            }
        }

        // The cost of the pass on the render thread (the time to record it, not the GPU's), for the log: what turning the
        // screen on costs the frame it first draws, and what it costs once running.
        private const int TimedPasses = 120;
        private static bool passTimed;
        private static int passCount;
        private static double passMillis, firstPassMillis;
        private static string timingWhy = "it was turned on";

        /// <summary>The next pass is timed for the log as a first one: the source was switched (<paramref name="why"/>).</summary>
        public static void Retime(string why)
        {
            timingWhy = why;
            passTimed = false;
        }

        /// <summary>Logs the first pass after the screen was turned on, and then the average of the next <see cref="TimedPasses"/>.</summary>
        private static void TimePass(bool first, long ticks)
        {
            double ms = Seconds(ticks) * 1000.0;
            if (first)
            {
                passTimed = true;
                passCount = 0;
                passMillis = 0.0;
                firstPassMillis = ms;
                Log.Info($"External view: the first pass after {timingWhy} took {ms:0.0} ms on the render thread" + (screenSetJustBuilt ? " (the pass's own screen resources were made then)" : " (its resources were already made)"));
                screenSetJustBuilt = false;
                timingWhy = "it was turned on";
                return;
            }
            if (passCount >= TimedPasses)
                return;
            passMillis += ms;
            if (++passCount == TimedPasses)
                Log.Info($"External view: the next {TimedPasses} passes took {passMillis / TimedPasses:0.0} ms each on the render thread (the first took {firstPassMillis:0.0} ms)");
        }

        /// <summary>A picture's half-angle tangents for a vertical field of view of <paramref name="field"/> radians, the picture's shape across.</summary>
        private static EnvMatrices.FovTangents Tangents(float field)
        {
            float v = (float)Math.Tan(field / 2.0);
            float h = v * TextureWidth / TextureHeight;
            return new EnvMatrices.FovTangents { Left = -h, Right = h, Up = v, Down = -v };
        }

        /// <summary>
        /// The picture changes what it is for: the zoom inset is placed where the head looks, the death view's screen is
        /// placed afresh, and the pass is timed again as a first one for the log.
        /// </summary>
        private static void Switched(Kind from, Kind to)
        {
            if (from == Kind.Death)
                DeathView.Ended();
            switch (to)
            {
                case Kind.Zoom:
                    ZoomInset.Place(EyeRenderer.Head);
                    Retime("the zoom inset came on");
                    break;
                case Kind.Death:
                    Retime("the death view came on");
                    break;
                case Kind.Screen:
                    if (from != Kind.None)
                        Retime("the screen came back");
                    break;
            }
        }

        /// <summary>
        /// The camera sent with the game camera this pass is relative to, as the eye-from-head matrix <see cref="EnvMatrices.MakeEye"/>
        /// takes, its vertical field of view in radians, the zoom, and what the picture was for in that frame.
        /// </summary>
        private static bool TryGetPose(object env, out Matrix eyeFromHead, out float field, out float zoom, out Kind kind)
        {
            eyeFromHead = Matrix.Identity;
            field = MathHelper.ToRadians(FieldOfViewDegrees);
            zoom = 1f;
            kind = Kind.None;
            MatrixD view = EnvMatrices.ViewD(env);
            long now = Stopwatch.GetTimestamp();
            lock (gate)
            {
                int newest = -1;
                for (int i = 1; i <= Capacity; i++)
                {
                    int index = (next - i + Capacity) % Capacity;
                    if (stamps[index] == 0 || Seconds(now - stamps[index]) > SnapshotSeconds)
                        continue;
                    if (newest < 0)
                        newest = index;
                    if (views[index] == view)
                    {
                        eyeFromHead = (Matrix)poses[index];
                        field = fields[index];
                        zoom = zooms[index];
                        kind = kinds[index];
                        return true;
                    }
                }
                if (newest < 0)
                    return false;
                // The camera the renderer holds is not among the recent ones: the newest chase camera is a frame off at worst.
                eyeFromHead = (Matrix)poses[newest];
                field = fields[newest];
                zoom = zooms[newest];
                kind = kinds[newest];
            }
            // Every frame is kept now, wanted or not: a miss is worth a line only when there is a picture to draw.
            if (kind != Kind.None && (++misses & (misses - 1)) == 0)
                Log.Warn($"External view: camera not found among the recent ones (miss {misses}); using the newest");
            return true;
        }

        /// <summary>The picture: made the first time, and again after the render size changes nothing about it (it has a size of its own).</summary>
        private static void EnsureTexture()
        {
            if (texture != null)
                return;
            texture = createRtv.Invoke(rwTextures.GetValue(null), new object[]
            {
                "VR external view", TextureWidth, TextureHeight, EyeRenderer.WindowFormat, 1, 0,
                SharpDX.Direct3D11.ResourceOptionFlags.None, SharpDX.Direct3D11.ResourceUsage.Default, 1, SharpDX.Direct3D11.CpuAccessFlags.None,
            });
            EyeRenderer.Clear(texture);
        }

        // ------------------------------------------------------------------------------------------------------
        // The pass's own screen-sized resources
        // ------------------------------------------------------------------------------------------------------

        /// <summary>
        /// A GBuffer, the light tiles and the auto-exposure pair at the picture's size, made with the renderer's own
        /// functions (MyGBuffer.Resize, MyLightsRendering.Resize) while the big ones are kept out of their way.
        /// The exposure starts from where the eyes' is, so the picture is not dark for the first second.
        /// </summary>
        private static void EnsureScreenSet()
        {
            if (screenSetBuilt)
                return;

            object big = gbufferMain.GetValue(null);
            object hdr = gbufferHdr.GetValue(null);
            object samples = gbufferSamples.GetValue(big);
            object quality = gbufferQuality.GetValue(big);
            object gbuffer = Activator.CreateInstance(gbufferType, nonPublic: true);
            gbufferResize.Invoke(gbuffer, new[] { TextureWidth, TextureHeight, samples, quality, hdr });

            object[] bigLights = new object[lightFields.Length];
            for (int i = 0; i < bigLights.Length; i++)
                bigLights[i] = lightFields[i].GetValue(null);
            object[] lights = new object[lightFields.Length];
            try
            {
                // Resize disposes what is there first: with nothing there, it builds the small set and leaves the big one alone.
                lightFields[0].SetValue(null, null);
                lightsResize.Invoke(null, new object[] { TextureWidth, TextureHeight });
                for (int i = 0; i < lights.Length; i++)
                    lights[i] = lightFields[i].GetValue(null);
            }
            finally
            {
                for (int i = 0; i < bigLights.Length; i++)
                    lightFields[i].SetValue(null, bigLights[i]);
            }

            Type rtvTexture = autoExposure.FieldType.GetElementType();
            Array exposure = Array.CreateInstance(rtvTexture, 2);
            object bigExposure = ((Array)autoExposure.GetValue(null)).GetValue(0);
            object rc = EyeRenderer.Context;
            for (int i = 0; i < 2; i++)
            {
                object created = createRtv.Invoke(rwTextures.GetValue(null), new object[]
                {
                    "AutoExposureExternal" + i, 1, 1, SharpDX.DXGI.Format.R32G32_Float, 1, 0,
                    SharpDX.Direct3D11.ResourceOptionFlags.None, SharpDX.Direct3D11.ResourceUsage.Default, 1, SharpDX.Direct3D11.CpuAccessFlags.None,
                });
                exposure.SetValue(created, i);
                copyResourceToResource.Invoke(rc, new[] { bigExposure, created });
            }

            smallGBuffer = gbuffer;
            smallLights = lights;
            smallExposure = exposure;
            screenSetBuilt = true;
            screenSetJustBuilt = true;
            Log.Info($"External view: screen resources made at {TextureWidth}x{TextureHeight}");
        }

        /// <summary>The renderer made its screen resources again (a new size, a new anti-aliasing mode): the small set is made again too, next time.</summary>
        private static void ScreenResourcesChanged()
        {
            if (!screenSetBuilt)
                return;
            screenSetBuilt = false;
            try
            {
                gbufferRelease.Invoke(smallGBuffer, null);

                object[] bigLights = new object[lightFields.Length];
                for (int i = 0; i < bigLights.Length; i++)
                    bigLights[i] = lightFields[i].GetValue(null);
                try
                {
                    for (int i = 0; i < smallLights.Length; i++)
                        lightFields[i].SetValue(null, smallLights[i]);
                    lightsDispose.Invoke(null, null);
                }
                finally
                {
                    for (int i = 0; i < bigLights.Length; i++)
                        lightFields[i].SetValue(null, bigLights[i]);
                }

                Array exposure = (Array)smallExposure;
                for (int i = 0; i < exposure.Length; i++)
                {
                    object[] args = { exposure.GetValue(i) };
                    disposeRtv.Invoke(rwTextures.GetValue(null), args);
                }
            }
            catch (Exception e)
            {
                Log.Error(e, "External view: freeing the screen resources failed");
            }
            smallGBuffer = null;
            smallLights = null;
            smallExposure = null;
        }

        /// <summary>
        /// MyActorOcclusionRenderer.Render issues the group occlusion queries for a cull query and stores their results in
        /// the actors, per view id - the main view's id, which the chase pass shares with the eyes. Skipped for the pass, so
        /// the eyes' queries and results are not overwritten with what the chase camera saw.
        /// </summary>
        private static bool SkipOcclusionQueries() => !drawing;

        /// <summary>
        /// The pass's culling must not take the eyes' occlusion results (what is hidden behind the cockpit from the head
        /// is not hidden from the chase camera). The eyes' pass keeps its own, written by their own queries.
        /// </summary>
        private static bool SkipOcclusion(ref bool __result)
        {
            if (!drawing)
                return true;
            __result = false;
            return false;
        }

        // ------------------------------------------------------------------------------------------------------
        // Showing the picture
        // ------------------------------------------------------------------------------------------------------

        /// <summary>
        /// The desktop: the picture over the lower left of each eye's part of the window (a quarter of its width at the
        /// screen's first size, in proportion to <see cref="VRSettings.ExternalViewSize"/>), after the eyes were copied into it. With a headset the window shows the left eye, so it shows the picture too.
        /// </summary>
        public static void ShowInWindow(object window, Vector2I windowSize)
        {
            if (frameKind == Kind.Zoom || frameKind == Kind.Death)
            {
                if (haveImage && drawnKind == frameKind)
                    ShowStandingInWindow(window, windowSize, StandingPose(), StandingWidth());
                return;
            }
            if (!Showing)
                return;
            for (int i = 0; i < 2; i++)
            {
                MyViewport area = EyeRenderer.Eyes[i].Window;
                if (area.Width <= 0f)
                    continue;
                float left = Math.Max(area.OffsetX, 0f), right = Math.Min(area.OffsetX + area.Width, windowSize.X);
                float top = Math.Max(area.OffsetY, 0f), bottom = Math.Min(area.OffsetY + area.Height, windowSize.Y);
                if (right - left < 16f || bottom - top < 16f)
                    continue;
                // A quarter of the eye's width at the screen's first size, and larger or smaller with it (the wrist panel's View size).
                float share = MathHelper.Clamp(0.25f * VRSettings.ExternalViewSize / VRSettings.ExternalViewSizeDefault, 0.1f, 0.5f);
                float width = (right - left) * share, height = width * TextureHeight / TextureWidth;
                float margin = (right - left) * 0.02f;
                EyeRenderer.CopyOpaque(window, texture, new MyViewport(left + margin, bottom - margin - height, width, height));
            }
        }

        /// <summary>The zoom inset's or the death view's screen in the tracking space, facing +z.</summary>
        private static Matrix StandingPose() => frameKind == Kind.Zoom ? ZoomInset.Pose : DeathView.Pose;

        /// <summary>The zoom inset's or the death view's screen's width, metres.</summary>
        private static float StandingWidth() => frameKind == Kind.Zoom ? ZoomInset.Width : DeathView.Width;

        /// <summary>
        /// The desktop: a screen standing in the tracking space (the zoom inset, the death view's) over each eye's part of the
        /// window where it stands in that eye, as the rectangle round its corners (<see cref="HudPanel.InWindow"/>: the window
        /// is a mirror, not drawn in perspective). One that would reach over into the other eye's half is left out of that eye.
        /// </summary>
        private static void ShowStandingInWindow(object window, Vector2I windowSize, in Matrix pose, float width)
        {
            Matrix inHead = pose * Matrix.Invert(EyeRenderer.Head);
            float halfWidth = width / 2f, halfHeight = halfWidth * TextureHeight / TextureWidth;
            for (int i = 0; i < 2; i++)
            {
                MyViewport area = EyeRenderer.Eyes[i].Window;
                if (area.Width <= 0f)
                    continue;
                MyViewport rect = HudPanel.InWindow(EyeRenderer.Eyes[i], inHead, halfWidth, halfHeight);
                if (rect.Width < 4f || rect.Height < 4f)
                    continue;
                float left = Math.Max(area.OffsetX, 0f), right = Math.Min(area.OffsetX + area.Width, windowSize.X);
                bool spills = left > 0.5f && rect.OffsetX < left - 0.5f
                              || right < windowSize.X - 0.5f && rect.OffsetX + rect.Width > right + 0.5f;
                if (!spills)
                    EyeRenderer.CopyOpaque(window, texture, rect);
            }
        }

        /// <summary>
        /// The headset: copies the picture into the screen's swapchain and places the screen on the dash, to be submitted
        /// with this frame (<see cref="TakeLayer"/>). The screen is put where the head is the first time it is shown, and
        /// stays there in the tracking space, which the game keeps in the cockpit.
        /// </summary>
        /// <param name="head">The head in the tracking space.</param>
        public static void ShowInHeadset(in Matrix head)
        {
            pending = null;
            if (frameKind == Kind.Zoom || frameKind == Kind.Death)
            {
                // The zoom inset or the death view stands in the screen's place; the dash screen keeps its own for after.
                // Neither can be taken hold of (Hands.ViewScreenGrab lets go of a screen that is not shown).
                lock (screenGate)
                    shown = false;
                if (!haveImage || drawnKind != frameKind || !XrSession.InFrame || !XrSession.ShouldRender)
                    return;
                try
                {
                    Submit(StandingPose(), StandingWidth());
                }
                catch (Exception e)
                {
                    available = false;
                    Log.Error(e, "External view: showing the zoom inset or the death view in the headset failed; the screen is off for the rest of the run");
                }
                return;
            }
            if (!Showing)
            {
                placed = false;
                lock (screenGate)
                    shown = false;
                return;
            }
            if (!XrSession.InFrame || !XrSession.ShouldRender)
                return;
            try
            {
                Matrix? moved;
                lock (screenGate)
                {
                    if (placeAgain)
                        placed = false;
                    placeAgain = false;
                    moved = movedTo;
                    movedTo = null;
                }
                if (!placed)
                {
                    anchor = Heading(head);
                    bool kept = TryKeptPlace(anchor, out dash);
                    if (!kept)
                        dash = Place(head);
                    placed = true;
                    Vector3 at = dash.Translation;
                    Log.Info($"External view: screen placed {(kept ? "where it was moved by hand" : "on the dash")} at ({at.X:0.00}, {at.Y:0.00}, {at.Z:0.00}) in the tracking space");
                }
                else if (moved.HasValue)
                {
                    dash = moved.Value;
                }
                lock (screenGate)
                {
                    shownPose = dash;
                    shownAnchor = anchor;
                    shown = true;
                }
                Submit(dash, VRSettings.ExternalViewSize);
            }
            catch (Exception e)
            {
                available = false;
                Log.Error(e, "External view: showing it in the headset failed; the screen is off for the rest of the run");
            }
        }

        /// <summary>Copies the picture into the screen's swapchain, to be submitted with this frame standing at <paramref name="pose"/>, <paramref name="width"/> metres wide.</summary>
        private static void Submit(in Matrix pose, float width)
        {
            SharpDX.Direct3D11.Texture2D image = XrSession.AcquireScreenImage(TextureWidth, TextureHeight);
            try
            {
                EyeRenderer.CopyToImage(texture, image);
            }
            finally
            {
                XrSession.ReleaseScreenImage();
            }
            Quaternion rotation = Quaternion.CreateFromRotationMatrix(pose);
            Vector3 position = pose.Translation;
            pending = new XrSession.Screen
            {
                Width = width,
                Height = width * TextureHeight / TextureWidth,
                Pose = new XrPosef
                {
                    Orientation = new XrQuaternionf { X = rotation.X, Y = rotation.Y, Z = rotation.Z, W = rotation.W },
                    Position = new XrVector3f { X = position.X, Y = position.Y, Z = position.Z },
                },
            };
        }

        /// <summary>The screen to submit with this headset frame, if there is one.</summary>
        public static XrSession.Screen? TakeLayer()
        {
            XrSession.Screen? layer = pending;
            pending = null;
            return layer;
        }

        /// <summary>
        /// The dash: <see cref="DashOffset"/> from the head along the horizon (the way it faces now), tilted to face
        /// the head. Panels in the tracking space face +z; <see cref="Matrix.CreateWorld"/> points -z along its forward.
        /// </summary>
        private static Matrix Place(in Matrix head)
        {
            Vector3 centre = Vector3.Transform(DashOffset, Heading(head));
            return Matrix.CreateWorld(centre, Vector3.Normalize(centre - head.Translation), Vector3.Up);
        }

        /// <summary>The head's place and its heading along the horizon (the way it faces now), level: what the screen's place is kept from.</summary>
        private static Matrix Heading(in Matrix head)
        {
            Vector3 forward = head.Forward;
            Vector3 along = new Vector3(forward.X, 0f, forward.Z);
            if (along.LengthSquared() < 0.04f)
            {
                Vector3 up = head.Up;
                along = forward.Y < 0f ? new Vector3(up.X, 0f, up.Z) : new Vector3(-up.X, 0f, -up.Z);
            }
            if (along.LengthSquared() < 1e-6f)
                along = Vector3.Forward;
            along.Normalize();
            return Matrix.CreateWorld(head.Translation, along, Vector3.Up);
        }

        // ------------------------------------------------------------------------------------------------------
        // Moving the screen by hand (Hands.ViewScreenGrab, on the game thread) and keeping where it was put
        // ------------------------------------------------------------------------------------------------------

        private static readonly object screenGate = new object();
        private static bool shown, placeAgain;
        private static Matrix shownPose, shownAnchor, anchor;
        private static Matrix? movedTo;

        /// <summary>Any thread: the screen is in the headset now, and where (in the tracking space, facing +z), with its width and height in metres.</summary>
        public static bool TryGetScreen(out Matrix pose, out float width, out float height)
        {
            width = VRSettings.ExternalViewSize;
            height = width * TextureHeight / TextureWidth;
            lock (screenGate)
            {
                pose = shownPose;
                return shown;
            }
        }

        /// <summary>Game thread, while a hand holds the screen: it stands here from the next headset frame.</summary>
        public static void MoveScreen(in Matrix pose)
        {
            lock (screenGate)
                movedTo = pose;
        }

        /// <summary>
        /// Game thread, as the hand lets go at <paramref name="pose"/>: keeps where it stands, from the head's heading when the
        /// screen appeared, in the settings file, so it appears there again (turned off and on, or in the next session).
        /// </summary>
        public static void KeepScreen(in Matrix pose)
        {
            Matrix from;
            lock (screenGate)
            {
                movedTo = pose;
                from = shownAnchor;
            }
            Matrix local = pose * Matrix.Invert(from);
            Quaternion turn = Quaternion.CreateFromRotationMatrix(local);
            Vector3 at = local.Translation;
            VRSettings.ExternalViewPlace = string.Join(" ", new[] { at.X, at.Y, at.Z, turn.X, turn.Y, turn.Z, turn.W }
                .Select(v => v.ToString("0.####", CultureInfo.InvariantCulture)));
        }

        /// <summary>Any thread: forgets where the screen was moved by hand; it goes back on the dash from the next headset frame.</summary>
        public static void PutScreenBack()
        {
            VRSettings.ExternalViewPlace = string.Empty;
            lock (screenGate)
            {
                placeAgain = true;
                movedTo = null;
            }
        }

        /// <summary>Where the screen was moved by hand, from <paramref name="heading"/> (<see cref="Heading"/>); false for the dash (none kept, or one that does not read).</summary>
        private static bool TryKeptPlace(in Matrix heading, out Matrix pose)
        {
            pose = Matrix.Identity;
            string kept = VRSettings.ExternalViewPlace;
            if (string.IsNullOrWhiteSpace(kept))
                return false;
            string[] parts = kept.Split(new[] { ' ' }, StringSplitOptions.RemoveEmptyEntries);
            if (parts.Length != 7)
                return false;
            var v = new float[7];
            for (int i = 0; i < 7; i++)
                if (!float.TryParse(parts[i], NumberStyles.Float, CultureInfo.InvariantCulture, out v[i]) || float.IsNaN(v[i]) || float.IsInfinity(v[i]))
                    return false;
            var at = new Vector3(v[0], v[1], v[2]);
            var turn = new Quaternion(v[3], v[4], v[5], v[6]);
            if (at.Length() > MaxPlaceDistance || turn.LengthSquared() < 0.5f)
                return false;
            turn.Normalize();
            Matrix local = Matrix.CreateFromQuaternion(turn);
            local.Translation = at;
            pose = local * heading;
            return true;
        }
    }
