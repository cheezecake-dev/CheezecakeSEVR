            managersType = Render11.GetType("VRage.Render11.Common.MyManagers", throwOnError: true);

            resolution = Field(render, "m_resolution");
            fullResViewport = Field(render, "FullResViewport");
            viewportResolution = AccessTools.Property(render, "ViewportResolution") ?? throw new MissingMemberException("MyRender11.ViewportResolution");
            debugOverrides = AccessTools.Property(render, "DebugOverrides") ?? throw new MissingMemberException("MyRender11.DebugOverrides");

            gbufferMain = Field(gbufferType, "Main");
            gbufferSamples = Field(gbufferType, "m_samplesCount");
            gbufferQuality = Field(gbufferType, "m_samplesQuality");
            gbufferHdr = Field(gbufferType, "m_hdrType");
            gbufferResize = AccessTools.Method(gbufferType, "Resize") ?? throw new MissingMemberException("MyGBuffer.Resize");
            gbufferRelease = AccessTools.Method(gbufferType, "Release") ?? throw new MissingMemberException("MyGBuffer.Release");

            lightFields = new[]
            {
